import type { Page } from "@playwright/test";
import { test, expect } from "./support/feature-test";
import { ensureLearnerUser } from "./support/keycloak";
import { e2eEmail, e2ePassword, kcBase, realm, webBase } from "./support/e2e-env";
import { login } from "./support/auth";

test.use({ locale: "de-DE" });

async function registrationFormJourney(page: Page) {
  await page.goto('/auth/login');
  await expect(page.locator('#kc-form-login')).toBeVisible();
  const registration = page.locator('a[href*="/login-actions/registration?"]');
  await expect(registration).toHaveCount(1);
  // Follow the session-bound link generated by Keycloak; never submit this form.
  const [response] = await Promise.all([
    page.waitForResponse(response => new URL(response.url()).pathname.endsWith('/login-actions/registration')),
    registration.click(),
  ]);
  expect(response.status()).toBe(200);
  await expect(page).toHaveTitle('Registrieren - GUSTAV');
  for (const field of ['display_name', 'email', 'password', 'password-confirm']) {
    await expect(page.locator(`#kc-register-form #${field}`)).toBeVisible();
  }
  await expect(page.locator('#password-requirements')).toContainText('8');
}

async function standardLoginJourney(page: Page) {
  const email = e2eEmail("auth.platform");
  await ensureLearnerUser(email, e2ePassword);
  await login(page, email, e2ePassword);
  await page.goto("/learning");
  await expect(page).toHaveURL(/\/learning/);
  const response = await page.request.get("/api/me");
  expect(response.status()).toBe(200);
  expect((await response.json()).roles).toContain("student");
  let tokenExposed = false;
  page.on('request', request => { if (new URL(request.url()).searchParams.has('id_token_hint')) tokenExposed = true; });
  await page.goto('/auth/logout');
  await page.getByRole('button', { name: 'Abmelden', exact: true }).click();
  await expect(page).toHaveURL(/\/auth\/logout\/success/);
  expect((await page.request.get('/api/me')).status()).toBe(401);
  expect(tokenExposed).toBe(false);
}

async function bcryptLoginJourney(page: Page) {
  const { execFileSync } = await import('node:child_process');
  const { ensureImportedBcryptLearner } = await import('./support/keycloak');
  const hash = execFileSync('../.venv/bin/python', ['-Wignore::DeprecationWarning', '-c', 'import crypt,sys; print(crypt.crypt(sys.stdin.read(), crypt.mksalt(crypt.METHOD_BLOWFISH)))'], { input: e2ePassword }).toString().trim();
  const email = e2eEmail('auth.bcrypt');
  await ensureImportedBcryptLearner(email, hash);
  await login(page, email, e2ePassword);
  await page.goto('/learning');
  await expect(page).toHaveURL(/\/learning/);
  expect((await page.request.get('/api/me')).status()).toBe(200);
}

async function recoveryJourney(page: Page) {
  const errorUrl = `${kcBase}/realms/${realm}/login-actions/action-token?key=invalid&pageRedirectUri=https://untrusted.example/`;
  const response = await page.goto(errorUrl);
  expect(response?.status()).toBe(400);
  const recovery = page.getByRole('link', { name: 'Erneut anmelden', exact: true });
  const passwordHelp = page.locator(`a[href="${webBase}/auth/forgot"]`);
  await expect(recovery).toHaveAttribute('href', `${webBase}/auth/login`);
  await expect(passwordHelp).toBeVisible();
  await expect(page.locator('a[href^="https://untrusted.example"]')).toHaveCount(0);

  // Open password help without sending mail or changing the realm SMTP settings.
  await passwordHelp.click();
  await expect(page.locator('input[name="username"]')).toBeVisible();
  await expect(page).toHaveURL(new RegExp(`${kcBase}/realms/${realm}/protocol/openid-connect/forgot-credentials`));

  await page.goto(errorUrl);
  await recovery.click();
  await page.locator('input[name="username"]').fill(e2eEmail('auth.platform'));
  await page.locator('input[name="password"]').fill(e2ePassword);
  await page.locator('button[type="submit"], input[type="submit"]').first().click();
  await expect.poll(async () => (await page.request.get('/api/me')).status()).toBe(200);
  await page.goto('/learning');
  await expect(page).toHaveURL(/\/learning/);
}

test("@feature-acceptance Keycloak preserves registration, standard and imported BCrypt logins and recovery links", async ({ page }) => {
  test.setTimeout(150_000);
  await test.step("Sichere Darstellung eines ungültigen Rücksprungs", async () => {
    await page.goto('/auth/callback?code=invalid');
    await expect(page).toHaveURL(/\/auth\/problem\?reason=invalid_code_or_state$/);
    await expect(page.getByRole('heading', { name: 'Anmeldevorgang abgelaufen' })).toBeVisible();
    await expect(page.getByText('invalid', { exact: true })).toHaveCount(0);
  });
  await test.step("Registrierung über den echten Login-Link ohne Mailversand", () => registrationFormJourney(page));
  await page.context().clearCookies();
  await test.step("Normale Anmeldung", () => standardLoginJourney(page));
  await page.context().clearCookies();
  await test.step("Wiederanmeldung und Passwort-Hilfe über sichere Recovery-Links", () => recoveryJourney(page));
  await page.context().clearCookies();
  await test.step("Übernommenes BCrypt-Passwort", () => bcryptLoginJourney(page));
});
